// ============================================================
// Tag.tsx - 标签组件
// 功能：显示一个带样式的标签，用于展示技术栈、分类等
// ============================================================

// 导入 React
import React from "react";

// ============================================================
// 定义 Props 类型
// ============================================================
interface TagProps {
  text: string;  // 标签文字（如："React"、"TypeScript"）
}

// ============================================================
// 主组件
// ============================================================
const Tag = ({ text }: TagProps) => {
  return (
    // 渲染为带 "tag" 类名的 span 元素
    // span 是行内元素，适合在文字中嵌入
    <span className="tag">
      {text}  {/* 显示传入的标签文字 */}
    </span>
  );
};

// ============================================================
// 导出组件
// ============================================================
export default Tag;